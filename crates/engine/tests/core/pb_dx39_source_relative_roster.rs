/// The `EffectFilter` variants whose `effect_applies_to` arm reads `effect.source`.
///
/// This list is PINNED here and DERIVED in R1 from `rules/layers.rs` itself, so the
/// definition of "source-relative" is the code's own, not this file's guess: a filter
/// is source-relative **iff** its match arm reads `effect.source`. R1 fails if the two
/// disagree in either direction.
const SOURCE_RELATIVE: &[&str] = &[
    "ArtifactsYouControl",
    "AttachedCreature",
    "AttachedLand",
    "AttachedPermanent",
    "AttackingCreaturesYouControl",
    "AttackingCreaturesYouControlWithSubtype",
    "CreaturesOpponentsControl",
    "CreaturesYouControl",
    "CreaturesYouControlExcludingSubtype",
    "CreaturesYouControlOfChosenColor",
    "CreaturesYouControlOfChosenType",
    "CreaturesYouControlWithColor",
    "CreaturesYouControlWithSubtype",
    "CreaturesYouControlWithSupertype",
    "LandsYouControl",
    "OtherCreaturesYouControl",
    "OtherCreaturesYouControlExcludingSubtype",
    "OtherCreaturesYouControlOfChosenType",
    "OtherCreaturesYouControlWithSubtype",
    "OtherCreaturesYouControlWithSubtypes",
];

/// The three `EffectFilter` variants that read the source's `attached_to` field —
/// axis (ii)'s subject (CR 301.5 Equipment, CR 301.6 Fortification, CR 303.4 Aura).
const ATTACHED_FILTERS: &[&str] = &["AttachedCreature", "AttachedLand", "AttachedPermanent"];

/// `Cost` variants that MOVE the source out of the battlefield as part of paying the
/// activation cost (CR 601.2h, reached for an activated ability by CR 602.2b). A
/// source-relative filter under any of these is *guaranteed* to resolve with the source
/// gone — it is not a race, it is certain.
///
/// **Not CR 118.12**, which the `/review` corrected: that rule is about a cost *"paid when
/// the spell or ability **resolves**"* (its own words), which is the opposite end of the
/// timeline from an activation cost and would have made the sentence above false.
///
/// The four are read off `pub enum Cost`; R3 prints which of them the corpus actually
/// uses, rather than assuming that "sacrifice" is the only shape in play.
const SOURCE_MOVING_COSTS: &[&str] = &[
    "SacrificeSelf",
    "ExileSelf",
    "DiscardSelf",
    "ExileSelfFromHand",
];

// ─────────────────────────────────────────────────────────────────────────────
// Generic JSON walk — total by construction
// ─────────────────────────────────────────────────────────────────────────────

/// The four keys every serialized `ContinuousEffectDef` carries. `condition` is
/// deliberately NOT required: it is `#[serde(default)]` and a future
/// `skip_serializing_if` would drop it, which must not blind the walk.
const CED_KEYS: &[&str] = &["layer", "modification", "filter", "duration"];

fn looks_like_ced(m: &Map<String, Value>) -> bool {
    CED_KEYS.iter().all(|k| m.contains_key(*k))
}

/// The variant name of an externally-tagged serde enum value.
///
/// Unit variants serialize to a bare string (`"CreaturesYouControl"`); every other
/// variant serializes to a one-key object (`{"CreaturesYouControlWithSubtype": ...}`).
fn variant_name(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Object(m) if m.len() == 1 => m.keys().next().expect("len == 1").clone(),
        other => format!("<not-an-enum:{other}>"),
    }
}

/// Collect every `ContinuousEffectDef`-shaped node in a JSON tree, with the '/'-joined
/// key path that reached it.
///
/// Recursion continues THROUGH a matched node: a `LayerModification::AddActivatedAbility`
/// carries an `ActivatedAbility` whose own effect may itself apply a continuous effect,
/// and stopping at the first match would lose it.
fn collect_ced(v: &Value, path: &mut Vec<String>, out: &mut Vec<(String, String)>) {
    match v {
        Value::Object(m) => {
            if looks_like_ced(m) {
                out.push((path.join("/"), variant_name(&m["filter"])));
            }
            for (k, child) in m {
                path.push(k.clone());
                collect_ced(child, path, out);
                path.pop();
            }
        }
        Value::Array(a) => {
            for (i, child) in a.iter().enumerate() {
                path.push(i.to_string());
                collect_ced(child, path, out);
                path.pop();
            }
        }
        _ => {}
    }
}

/// Every string leaf in a JSON tree — used to spot unit-variant `Cost`s at any nesting
/// depth, so `Cost::Sequence([Mana, SacrificeSelf])` is found without a `Sequence` arm.
fn string_leaves(v: &Value, out: &mut BTreeSet<String>) {
    match v {
        Value::String(s) => {
            out.insert(s.clone());
        }
        Value::Object(m) => {
            for child in m.values() {
                string_leaves(child, out);
            }
        }
        Value::Array(a) => {
            for child in a {
                string_leaves(child, out);
            }
        }
        _ => {}
    }
}

/// Which `ContinuousEffectDef` site a JSON path landed on.
///
/// The three sites in `card_definition.rs` (R7 pins that there are exactly three):
/// * `AbilityDefinition::Static { continuous_effect }` — CR 611.3a, NOT locked in.
/// * `Effect::ApplyContinuousEffect { effect_def }` — CR 611.2c, locked in at resolution.
/// * `Effect::CreateEmblem { static_effects }` — CR 114.5: an emblem *"is neither a card
///   nor a permanent"*, and CR 114.2 puts it into the command zone. **That an emblem never
///   LEAVES the command zone is an engine measurement, not a rule** — no CR rule says it,
///   and the `/review` was right to refuse the claim: what is true is that nothing in
///   `effects/mod.rs` ever moves an emblem out, so CR 400.7 never retires its `ObjectId`
///   and its source cannot go missing. Recorded separately, not in scope.
fn site_of(path: &str) -> &'static str {
    let segs: Vec<&str> = path.split('/').collect();
    if segs.contains(&"effect_def") {
        "resolution"
    } else if segs.contains(&"static_effects") {
        "emblem"
    } else if path == "Static/continuous_effect" {
        "static"
    } else {
        "unclassified"
    }
}

