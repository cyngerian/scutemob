//! PB-DX39 (`OOS-DX5-3` + `OOS-DX5-7`'s residual) corpus census — **source-relative
//! `EffectFilter`s and the last-known-information hole underneath them.**
//!
//! `rules/layers.rs::effect_applies_to` answers ~20 of its `EffectFilter` arms by
//! reading the effect's SOURCE object out of `state.objects` — its `controller`, its
//! `attached_to`, its `chosen_creature_type`, its `chosen_color`. Every one of those
//! arms answers `false` unconditionally when `state.objects.get(&source_id)` returns
//! `None`, i.e. once the source has left the battlefield.
//!
//! For a continuous effect generated by the RESOLUTION of a spell or ability
//! (CR 611.2c), the affected set is snapshotted at resolution by
//! `rules/layers.rs::snapshot_affected_set`. If the source is already gone by then,
//! that set comes out EMPTY and the effect does nothing at all. CR 608.2h and
//! CR 113.7a say it must instead answer from the source's **last known information**:
//! the ability exists independently of its source, and the source's characteristics
//! are those it last had on the battlefield.
//!
//! Two subjects this file exists to size:
//!
//! * `umezawas_jitte` — mode 0 is `EffectFilter::AttachedCreature` on an ACTIVATED
//!   ability. Gatherer ruling 2005-02-01: *"If the Jitte leaves the battlefield after
//!   the '+2/+2' mode is announced but before it resolves, the bonus is given to the
//!   creature that was most recently equipped once the ability resolves."*
//! * `mardu_ascendancy` — `Cost::SacrificeSelf` plus `EffectFilter::CreaturesYouControl`.
//!   The source sacrifices ITSELF as the cost, so it is *always* gone at resolution:
//!   the printed +0/+3 currently applies to NOBODY, every time.
//!
//! ## What this file measures
//!
//! | row | what it pins |
//! |---|---|
//! | R1 | the source-relative filter set, DERIVED from `layers.rs` rather than listed |
//! | R2 | every declared `EffectFilter` variant is classified by exactly one match arm |
//! | R3 | axis (i) — SACRIFICE-SELF: source-relative filter under a source-moving cost |
//! | R4 | axis (ii) — ATTACHED, split into resolution-time (in scope) and static (not) |
//! | R5 | axis (iii) — CONTROL: `AbilityDefinition::Spell` members, which must NOT move |
//! | R6 | the INVERSE ORACLE axis, and how far it fails to nest with the structural one |
//! | R7 | source gate: the three `ContinuousEffectDef` sites the walk must reach |
//! | R8 | source gate: the `Effect` nesting forms, recorded rather than relied upon |
//!
//! ## SR-36, and how the walk is enumerated
//!
//! Every population here is derived by enumerating `mtg_engine::all_cards()`. Nothing
//! is grepped out of `crates/card-defs/`: a variant named only inside a `// TODO`
//! comment is counted by a grep and is not in the corpus, which is the failure mode
//! `OOS-CARDS2-7`, `OOS-DX47-2`, PB-DX48 and PB-DX49 each recorded in turn.
//!
//! **The `Effect` nesting sites are not hand-listed, and deliberately so.** PB-DX26's
//! `/review` found an eleventh nesting site (`Effect::RollDice`'s
//! `Vec<(u32, u32, Effect)>`) that a hand-written `Box`/`Vec` count had missed, and
//! PB-DX26's walk carried a `_ => false` arm that could go shallow in silence. This
//! file walks the SERIALIZED form instead: each `AbilityDefinition` is turned into a
//! `serde_json::Value` and the resulting tree is walked generically, recording every
//! node that is shaped like a `ContinuousEffectDef` (an object carrying all four of
//! `layer` / `modification` / `filter` / `duration`). A generic JSON walk is total by
//! construction — it reaches a new `Effect` variant, a new `Vec<(..., Effect)>` tuple
//! form and a new `ContinuousEffectDef` site on the day each is added, with no arm to
//! forget. R8 records the source-level nesting forms as EVIDENCE of the enumeration,
//! not as the mechanism.
//!
//! ## CR citations (Architecture Invariant 8)
//!
//! * CR 611.2c — a continuous effect from a resolving spell or ability affects a set of
//!   objects determined when the effect begins; the set does not change afterwards.
//! * CR 608.2h — if an effect requires information about the game, it uses the current
//!   information, or last known information where the object has left the zone.
//! * CR 113.7a — an ability on the stack exists independently of its source.
//! * CR 611.3a — a continuous effect from a STATIC ability is not locked in; it applies
//!   continuously while the source is on the battlefield, so it has no LKI problem.
//!
//! **What membership asserts, and does NOT assert** (PB-DX4's `BASELINE` lesson):
//! membership means only that this def carries this shape. It says nothing about
//! whether the def is otherwise oracle-correct.

use mtg_engine::{all_cards, CardDefinition};
use serde_json::{Map, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

