/// Every oracle text a def carries — front face, back face AND adventure half.
///
/// PB-DX8 measured that reading `def.oracle_text` alone is blind to every transformed
/// face and every Adventure half, so all three are read here.
fn oracle_texts(def: &CardDefinition) -> Vec<(&'static str, String)> {
    let mut v = vec![("front", def.oracle_text.clone())];
    if let Some(f) = &def.back_face {
        v.push(("back", f.oracle_text.clone()));
    }
    if let Some(f) = &def.adventure_face {
        v.push(("adventure", f.oracle_text.clone()));
    }
    v
}

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct OracleHit {
    card_name: String,
    completeness: String,
    deck_legal: bool,
    face: String,
    line: String,
    cue: String,
}

/// The INVERSE axis: printed text that promises an "until end of turn" pump on an
/// ability whose cost sacrifices something or equips something.
///
/// Matched case-insensitively, per oracle LINE (oracle text puts one ability per line),
/// so "sacrifice" in one ability and "until end of turn" in another do not pair up.
///
/// This axis and the structural one **do not nest**, in either direction — PB-DX26,
/// PB-DX43 and PB-DX15a each recorded a batch that reported one as if it contained the
/// other. R6 prints both differences rather than a single overlap count.
fn oracle_axis() -> Vec<OracleHit> {
    let mut out = Vec::new();
    for def in all_cards() {
        for (face, text) in oracle_texts(&def) {
            for line in text.split('\n') {
                let lc = line.to_lowercase();
                if !lc.contains("until end of turn") {
                    continue;
                }
                let cue = if lc.contains("sacrifice") {
                    "sacrifice"
                } else if lc.contains("equip") {
                    "equip"
                } else {
                    continue;
                };
                out.push(OracleHit {
                    card_name: def.name.clone(),
                    completeness: def.completeness.kind().to_string(),
                    deck_legal: def.completeness.is_complete(),
                    face: face.to_string(),
                    line: line.trim().to_string(),
                    cue: cue.to_string(),
                });
            }
        }
    }
    out.sort();
    out.dedup();
    out
}

