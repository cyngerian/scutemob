/// The corpus size floor. Every assertion in this file could be satisfied by an
/// empty scan, so each one asserts this first: a walk that returns nothing must
/// not be able to pass by reporting an empty set.
const CORPUS_FLOOR: usize = 1_800;

fn assert_denominator() -> usize {
    let n = all_cards().len();
    assert!(
        n >= CORPUS_FLOOR,
        "non-vacuity floor: all_cards() returned {n} defs, expected >= {CORPUS_FLOOR}. \
         A broken walk that scans nothing must not be able to satisfy the roster pins."
    );
    n
}

