#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Occurrence {
    card_name: String,
    card_id: String,
    completeness: String,
    deck_legal: bool,
    face: String,
    ability_index: usize,
    ability_kind: String,
    /// Which of `SOURCE_MOVING_COSTS` this ability's cost carries, if any.
    source_moving_costs: Vec<String>,
    cost: String,
    filter: String,
    site: &'static str,
    path: String,
}

impl Occurrence {
    fn legal_tag(&self) -> &'static str {
        if self.deck_legal {
            "DECK-LEGAL"
        } else {
            "not-legal "
        }
    }
}

fn faces_of(def: &CardDefinition) -> Vec<(&'static str, &Vec<mtg_engine::AbilityDefinition>)> {
    let mut v: Vec<(&'static str, &Vec<mtg_engine::AbilityDefinition>)> =
        vec![("front", &def.abilities)];
    if let Some(f) = &def.back_face {
        v.push(("back", &f.abilities));
    }
    if let Some(f) = &def.adventure_face {
        v.push(("adventure", &f.abilities));
    }
    v
}

/// Every `(def, ability, source-relative filter)` triple in the corpus.
fn census() -> Vec<Occurrence> {
    let mut out = Vec::new();
    let source_relative: BTreeSet<&str> = SOURCE_RELATIVE.iter().copied().collect();

    for def in all_cards() {
        for (face, abilities) in faces_of(&def) {
            for (ability_index, ability) in abilities.iter().enumerate() {
                let json =
                    serde_json::to_value(ability).expect("AbilityDefinition derives Serialize");
                let ability_kind = variant_name(&json);

                // The ability's own cost field, if the variant has one.
                let cost_value: Option<&Value> = match &json {
                    Value::Object(m) if m.len() == 1 => {
                        m.values().next().and_then(|inner| inner.get("cost"))
                    }
                    _ => None,
                };
                let mut cost_strings = BTreeSet::new();
                if let Some(c) = cost_value {
                    string_leaves(c, &mut cost_strings);
                }
                let source_moving_costs: Vec<String> = SOURCE_MOVING_COSTS
                    .iter()
                    .filter(|m| cost_strings.contains(**m))
                    .map(|m| (*m).to_string())
                    .collect();
                let cost = cost_value
                    .map(|c| {
                        let s = serde_json::to_string(c).unwrap_or_default();
                        if s.len() > 70 {
                            format!("{}…", &s[..70])
                        } else {
                            s
                        }
                    })
                    .unwrap_or_else(|| "-".to_string());

                let mut found = Vec::new();
                collect_ced(&json, &mut Vec::new(), &mut found);
                for (path, filter) in found {
                    if !source_relative.contains(filter.as_str()) {
                        continue;
                    }
                    out.push(Occurrence {
                        card_name: def.name.clone(),
                        card_id: def.card_id.0.clone(),
                        completeness: def.completeness.kind().to_string(),
                        deck_legal: def.completeness.is_complete(),
                        face: face.to_string(),
                        ability_index,
                        ability_kind: ability_kind.clone(),
                        source_moving_costs: source_moving_costs.clone(),
                        cost: cost.clone(),
                        filter,
                        site: site_of(&path),
                        path,
                    });
                }
            }
        }
    }
    out.sort();
    out
}

fn names(occ: &[&Occurrence]) -> Vec<String> {
    let mut v: Vec<String> = occ.iter().map(|o| o.card_name.clone()).collect();
    v.sort();
    v.dedup();
    v
}

fn print_rows(label: &str, rows: &[&Occurrence]) {
    println!("\n── {label} ── ({} occurrences)", rows.len());
    if rows.is_empty() {
        println!("   (none)");
        return;
    }
    for o in rows {
        println!(
            "   {name:<34} [{legal}] {comp:<11} {face:<9} ab#{idx} {kind:<10} filter={filter:<42} site={site:<11} cost={cost}",
            name = o.card_name,
            legal = o.legal_tag(),
            comp = o.completeness,
            face = o.face,
            idx = o.ability_index,
            kind = o.ability_kind,
            filter = o.filter,
            site = o.site,
            cost = o.cost,
        );
        println!("      card_id={} path={}", o.card_id, o.path);
    }
}

