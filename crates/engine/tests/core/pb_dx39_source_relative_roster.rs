/// Axis (i): a source-relative filter reached at RESOLUTION time under a cost that
/// moves the source. Always live-wrong — the source is gone by construction.
fn axis_sacrifice_self(c: &[Occurrence]) -> Vec<&Occurrence> {
    c.iter()
        .filter(|o| !o.source_moving_costs.is_empty())
        .collect()
}

/// Axis (ii), in-scope half: an attached-to filter reached at RESOLUTION time.
fn axis_attached_resolution(c: &[Occurrence]) -> Vec<&Occurrence> {
    c.iter()
        .filter(|o| ATTACHED_FILTERS.contains(&o.filter.as_str()) && o.site == "resolution")
        .collect()
}

/// Axis (ii), out-of-scope half: the same filters on a STATIC ability.
///
/// CR 611.3a: a static ability's continuous effect is not locked in, and its source is
/// on the battlefield by construction — **CR 611.3b**, *"the effect applies at all times
/// that the permanent generating it is on the battlefield"*, which is the rule for a
/// STATIC ability. (CR 611.2b, which this line cited until the `/review`, is about the
/// *"for as long as"* durations of an effect generated by a RESOLUTION.) These are
/// printed so the distinction is visible, and asserted so they cannot drift into scope
/// unnoticed.
fn axis_attached_static(c: &[Occurrence]) -> Vec<&Occurrence> {
    c.iter()
        .filter(|o| ATTACHED_FILTERS.contains(&o.filter.as_str()) && o.site == "static")
        .collect()
}

/// Axis (iii): the CONTROL population — a spell's own resolution effect.
///
/// PB-DX5 already fixed these by snapshotting the affected set during resolution while
/// the spell is still in `state.objects`. They must stay green; the census prints them
/// so a future batch can see the class did not move.
fn axis_control_spell(c: &[Occurrence]) -> Vec<&Occurrence> {
    c.iter().filter(|o| o.ability_kind == "Spell").collect()
}

