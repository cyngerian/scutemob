//! PB-DX39 (`OOS-DX5-3`, `OOS-DX5-7`): gates for the ONE source-relative arithmetic and
//! for the last-known-information store that feeds it.
//!
//! ## What the batch did, in one paragraph
//!
//! `rules::layers::effect_applies_to` has 37 `EffectFilter` arms, of which **20 are
//! source-relative**: they need the effect's SOURCE object's `controller`, `attached_to`,
//! `chosen_creature_type` or `chosen_color`. Each of the 20 re-read
//! `state.objects.get(&source_id)` for itself and answered `false` when that returned
//! `None` — so once the source left the battlefield (CR 400.7 retires its id), every one of
//! them matched nothing. For a **resolution-generated** effect that is CR-wrong: CR 608.2h
//! says the effect *"uses the object's last known information"* once the source *"is no
//! longer in [the] zone [it was expected to be in]"*, and CR 113.7a says the ability
//! *"exists on the stack independently of its source"*. Two deck-legal subjects were live-
//! wrong: Umezawa's Jitte's `+2/+2` mode (destroy the Jitte in response and the bonus went
//! nowhere) and Mardu Ascendancy's `+0/+3` (a `Cost::SacrificeSelf` ability, so its source
//! is ALWAYS gone at resolution — wrong in every game).
//!
//! Twenty reads became **two constructors** consumed by one threaded parameter.
//!
//! ## The scoping is the design, not caution
//!
//! There are two constructors and they carry two different CR justifications:
//!
//! * `source_view_at_resolution` — live first, **then LKI**. CR 608.2h / CR 113.7a. Called
//!   from `snapshot_affected_set` and nowhere else, because that is the CR 611.2c
//!   determination for an effect generated by the RESOLUTION of a spell or ability.
//! * `source_view_live` — live only, **no LKI fallback**. CR 611.3a: a static ability's
//!   effect *"isn't 'locked in'"* and exists only while the ability does, which means only
//!   while the object does. An LKI fallback there would make a departed permanent's static
//!   ability run for the rest of the game.
//!
//! `is_effect_active`'s `EffectDuration::WhileSourceOnBattlefield` arm already refuses the
//! common case, but it does not cover every duration a static registration can carry:
//! `rules/replacement.rs` and the `StackObjectKind::ClassLevelAbility` arm of
//! `rules/resolution.rs` both forward a card def's own duration verbatim, and
//! `Effect::CreateEmblem`'s static loop uses `EffectDuration::Indefinite`. `r7` measures
//! how much of that hypothetical the corpus actually contains, and ratchets it, because a
//! **zero measured** is worth more than a risk argued.
//!
//! ## Rows
//!
//! * **`r1`** — the mechanism gate the acceptance criterion asks for: no arm of
//!   `effect_applies_to_inner` may read the source directly again. Two independent axes
//!   (`OOS-DX36-8`: a survivor scan has a SHAPE axis and a SPELLING axis, and varying one
//!   while holding the other is half a check).
//! * **`r2`** — the 20 source-relative arms, pinned by NAME SET and not by count. A count
//!   assertion passes when one member leaves and another joins.
//! * **`r3`** — the SR-24 successor. That gate's own comment said *"Adding a NEW READER
//!   that consults a fifth snapshot keyword is NOT machine-caught"*. It is now: every
//!   reader of `lki_objects` / `lki_object_snapshot` in the whole workspace is pinned.
//! * **`r4`** — `is_effect_active`'s two source reads stay LIVE-ONLY, so a later batch
//!   cannot "finish the job" and make a departed source's static ability immortal.
//! * **`r5`** — `source_view_at_resolution` has exactly ONE caller and it is
//!   `snapshot_affected_set`. Without this, "the fallback is locked-path only" is a
//!   comment, and this batch's whole subject is that a comment is a claim.
//! * **`r6`** — the capture/clear coupling: everything
//!   `GameState::is_source_of_a_pending_ability` captures FOR is something
//!   `maybe_clear_lki_objects` waits ON, so a snapshot lives exactly as long as the ability
//!   that needs it.
//! * **`r7`** — the corpus census the scoping rests on, ratcheted.
//! * **`t_census_report`** — PRINTS every population above under `--nocapture`. PB-DX8's
//!   rule: a figure that no test prints is a figure that was transcribed.
//!
//! ## Why the walks are walks
//!
//! `r3` and `r5` walk **every `<crate>/src` and `<tool>/src` in the workspace**, reusing
//! `pb_dx49_saga_blanking_roster::workspace_src_files_checked`. PB-DX48's `SITE_SRCS` named
//! six `rules/` files while the function it policed was `pub(crate)` and was defeated by a
//! consumer one crate over; PB-DX49's own first draft walked one crate and was defeated the
//! same way. `r7` walks `all_cards()`, never card source (SR-36).

