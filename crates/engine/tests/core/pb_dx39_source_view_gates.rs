fn workspace_root() -> PathBuf {
    let mut p = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    // crates/engine -> crates -> workspace root
    p.pop();
    p.pop();
    p
}

fn read_engine_file(rel: &str) -> String {
    let path = workspace_root().join(rel);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}

/// `src` with every comment replaced by spaces and then **all whitespace removed**.
///
/// Two properties this buys, both of them the point:
/// * multi-line tolerance — `state\n    .objects\n    .get(&source_id)` squeezes to exactly
///   the same bytes as the one-line spelling. Three of the twenty arms (`AttachedCreature`,
///   `AttachedLand`, `AttachedPermanent`) spelled the read across line breaks at HEAD, which
///   is `OOS-DX50`'s multi-line lesson and is why the task brief's census of "17 occurrences"
///   was a floor and the truth was 20.
/// * receiver-agnosticism — a `use` alias or a differently-named binding
///   (`st.objects.get(&source_id)`) still contains `.objects.get(&source_id)`.
fn squeeze(src: &str) -> String {
    strip_comments(src)
        .chars()
        .filter(|c| !c.is_whitespace())
        .collect()
}

/// `strip_comments`, then every `"..."` string literal blanked.
///
/// Necessary rather than fastidious: `state/diagnostics.rs`'s SR-23 `debug_assert!`
/// messages *quote* `GameState::lki_object_snapshot` to point an author at the right
/// vocabulary. A walk that counts those as readers is counting guidance prose, which is
/// `OOS-CARDS2-7` / `OOS-DX47-2`'s shape one layer over.
fn strip_comments_and_strings(src: &str) -> String {
    let stripped = strip_comments(src);
    let b = stripped.as_bytes();
    let mut out = String::with_capacity(stripped.len());
    let mut i = 0usize;
    while i < b.len() {
        if b[i] == b'"' {
            out.push(' ');
            i += 1;
            while i < b.len() && b[i] != b'"' {
                if b[i] == b'\\' {
                    out.push(' ');
                    i += 1;
                }
                out.push(if b[i] == b'\n' { '\n' } else { ' ' });
                i += 1;
            }
            if i < b.len() {
                out.push(' ');
                i += 1;
            }
        } else {
            let ch = stripped[i..].chars().next().expect("char boundary");
            out.push_str(&stripped[i..i + ch.len_utf8()]);
            i += ch.len_utf8();
        }
    }
    out
}

/// [`strip_comments_and_strings`], with every `#[cfg(test)] mod ... { .. }` body blanked.
///
/// The site rosters below are about **production** readers. An in-source unit module that
/// drives a departure and then asserts on `lki_object_snapshot` is doing exactly what a
/// test should do, and making every such probe redden a roster would train the next author
/// to stop writing them.
fn production_source(src: &str) -> String {
    let mut out = strip_comments_and_strings(src);
    while let Some(at) = out.find("#[cfg(test)]") {
        let Some(rel) = out[at..].find('{') else {
            break;
        };
        let open = at + rel;
        let Some(end) = matching_brace(&out, open) else {
            break;
        };
        let blanked: String = out[at..=end]
            .chars()
            .map(|c| if c == '\n' { '\n' } else { ' ' })
            .collect();
        out.replace_range(at..=end, &blanked);
    }
    out
}

/// The offset of the `}` matching the `{` at `open`. `None` on unbalanced input, so every
/// caller fails **closed** rather than falling back to a byte window (`OOS-DX49-2`).
fn matching_brace(src: &str, open: usize) -> Option<usize> {
    let b = src.as_bytes();
    if b.get(open) != Some(&b'{') {
        return None;
    }
    let mut depth = 0usize;
    let mut i = open;
    while i < b.len() {
        match b[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            b'"' => {
                i += 1;
                while i < b.len() && b[i] != b'"' {
                    if b[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
            }
            _ => {}
        }
        i += 1;
    }
    None
}

/// The comment-stripped body of the named free function in the given engine file,
/// brace-matched. Fails closed.
fn fn_body(rel: &str, name: &str) -> String {
    let src = strip_comments(&read_engine_file(rel));
    let needle = format!("fn {name}(");
    let at = src
        .find(&needle)
        .unwrap_or_else(|| panic!("PB-DX39: `{needle}` not found in {rel} -- renamed?"));
    let open = src[at..]
        .find('{')
        .map(|o| at + o)
        .unwrap_or_else(|| panic!("PB-DX39: no body brace for `{name}` in {rel}"));
    let end = matching_brace(&src, open)
        .unwrap_or_else(|| panic!("PB-DX39: could not brace-match `{name}` in {rel}"));
    src[open..=end].to_string()
}

/// The enclosing function's name for byte offset `at`: the last `fn <name>` at or before
/// `at`. Used by the workspace walks so a site is attributed, not merely counted.
fn enclosing_fn_name(src: &str, at: usize) -> String {
    let head = &src[..at];
    // A site that IS a definition (`fn source_view_at_resolution(`) has `fn ` immediately
    // before it, so the generic rule below would attribute it to the empty string. Name it
    // after itself instead, so a definition and its callers are distinguishable rows.
    if head.ends_with("fn ") {
        return src[at..]
            .chars()
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect();
    }
    match head.rfind("fn ") {
        Some(i) => head[i + 3..]
            .chars()
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect(),
        None => "<top-level>".to_string(),
    }
}

