///   force the distinction**: no CR rule says an emblem never leaves the command zone
///   (CR 114.1 defines what an emblem is, CR 114.3 that it has no other characteristics,
///   CR 114.4 that its abilities function there — none of them says it cannot move). What
///   is true is measurable: `effects/mod.rs`'s emblem construction places it in
///   `ZoneId::Command(controller)` and **nothing in the engine ever moves it out**, so its
///   `ObjectId` is never retired (CR 400.7 never fires on it), `source_view_live`'s lookup
///   always succeeds, and the fallback is unreachable for these four **whichever
///   constructor they used**. They are the SHAPE without the exposure — and if a later
///   batch teaches the engine to move an emblem, that measurement expires and this ratchet
///   is the thing that should stop being trusted.
///
/// So this row is not evidence that the scoping saved a live defect today. It is evidence
/// that the shape exists in the corpus, that the only thing keeping it harmless is a
/// property of emblems rather than anything about the filter, and that a fifth member
/// arriving under the other holder would be a real one.
const MAX_UNPROTECTED_STATIC_REGISTRATIONS: usize = 0;
const MAX_UNPROTECTED_EMBLEM_REGISTRATIONS: usize = 4;

/// Source-relative + live path + a duration `is_effect_active` does NOT already refuse.
///
/// `WhileSourceOnBattlefield` members are excluded because `is_effect_active` returns
/// `false` for them the moment the source leaves, so no source view of any kind is ever
/// consulted. That exclusion is *why* the residual is the interesting set: it is exactly
/// what `is_effect_active` does not protect.
fn unprotected_live_registrations() -> Vec<(&'static str, String)> {
    let source_relative: BTreeSet<String> =
        SOURCE_RELATIVE_ARMS.iter().map(|s| s.to_string()).collect();
    live_path_registrations()
        .into_iter()
        .filter(|r| source_relative.contains(&r.filter) && r.duration != "WhileSourceOnBattlefield")
        .map(|r| {
            (
                r.holder,
                format!("{} [{}] {} / {}", r.card, r.holder, r.filter, r.duration),
            )
        })
        .collect()
}

/// CR 611.3a / CR 114.5: the population the two-constructor split protects, ratcheted per
/// holder.
#[test]
fn r7_no_unprotected_live_path_source_relative_registration() {
    let members = unprotected_live_registrations();
    let statics: Vec<&String> = members
        .iter()
        .filter(|(h, _)| *h == "AbilityDefinition::Static")
        .map(|(_, m)| m)
        .collect();
    let emblems: Vec<&String> = members
        .iter()
        .filter(|(h, _)| *h == "Effect::CreateEmblem")
        .map(|(_, m)| m)
        .collect();

    // `==` rather than `<=`: the ratchet is zero, so `<=` is an absurd comparison (clippy
    // says so, and it is right). Equality is also the stronger statement -- it fails in
    // BOTH directions, and from zero the downward direction cannot occur.
    assert!(
        statics.len() == MAX_UNPROTECTED_STATIC_REGISTRATIONS,
        "PB-DX39 r7: {} card def(s) register a SOURCE-RELATIVE continuous effect from an \
         `AbilityDefinition::Static` (CR 611.3a) with a duration other than \
         `WhileSourceOnBattlefield`, above the ratchet of {}. That source is a PERMANENT and \
         can leave the battlefield, and `is_effect_active` will not refuse the effect once \
         it has -- so this is the class for which `source_view_live` having NO \
         last-known-information fallback is load-bearing. With an unconditional fallback \
         each of these would keep applying from the graveyard for the rest of the game. \
         Members: {statics:#?}",
        statics.len(),
        MAX_UNPROTECTED_STATIC_REGISTRATIONS
    );
    assert!(
        emblems.len() <= MAX_UNPROTECTED_EMBLEM_REGISTRATIONS,
        "PB-DX39 r7: {} emblem static effect(s) pair a source-relative filter with a \
         non-`WhileSourceOnBattlefield` duration, above the ratchet of {}. These are \
         harmless only because NOTHING IN THE ENGINE ever moves an emblem out of the \
         command zone (a measurement, not a rule -- CR 114 says an emblem is put there and \
         that its abilities function there, and says nothing about it staying), so its \
         `ObjectId` is never retired. Confirm that still holds for the new member (an \
         emblem that can leave would be the first real instance of this class) and then \
         raise the ratchet with that measurement stated. Members: {emblems:#?}",
        emblems.len(),
        MAX_UNPROTECTED_EMBLEM_REGISTRATIONS
    );
    // The emblem ratchet is a CEILING, and a ceiling with slack is where a regression hides
    // (PB-DX49's lesson). Pin the floor too, so a member silently LEAVING this set -- which
    // would mean the corpus changed under the reasoning above -- is also visible.
    assert_eq!(
        emblems.len(),
        MAX_UNPROTECTED_EMBLEM_REGISTRATIONS,
        "PB-DX39 r7: the emblem population moved DOWN to {}. That is not a problem, but the \
         reasoning in this row's doc names these members explicitly; re-take the figure and \
         lower the ratchet rather than leaving slack. Members: {emblems:#?}",
        emblems.len()
    );

    // Non-vacuity floor: the walk must find live-path registrations at all, or the filters
    // above are selecting from an empty set and both ratchets measure nothing. Measured at
    // HEAD: 209 registrations, 188 of them source-relative.
    let all = live_path_registrations();
    assert!(
        all.len() >= 100,
        "PB-DX39 r7: the `all_cards()` walk found only {} live-path continuous-effect \
         registrations (209 at HEAD); the walk has gone vacuous",
        all.len()
    );
    let source_relative: BTreeSet<String> =
        SOURCE_RELATIVE_ARMS.iter().map(|s| s.to_string()).collect();
    assert!(
        all.iter()
            .filter(|r| source_relative.contains(&r.filter))
            .count()
            >= 100,
        "PB-DX39 r7: fewer than 100 of the live-path registrations are source-relative (188 \
         at HEAD); either the corpus moved a great deal or the filter-name extraction has \
         broken and both ratchets are selecting from noise"
    );
}

