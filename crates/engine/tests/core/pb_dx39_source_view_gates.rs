// r1 — the mechanism gate
// ─────────────────────────────────────────────────────────────────────────────

/// Whitespace-free spellings of a direct source read. AXIS 1 (SPELLING).
///
/// Receiver-agnostic by construction: the needles start at the `.objects` / `.object(`
/// segment, so `state.objects.get(&source_id)`, `st.objects.get(&source_id)` and a
/// `use`-aliased receiver all match the same bytes.
const DIRECT_SOURCE_READ_NEEDLES: &[&str] = &[
    ".objects.get(&source_id)",
    ".objects.get(&sid)",
    ".objects.get(&src_id)",
    ".objects.get_mut(&source_id)",
    ".object(source_id)",
    ".expect_object(source_id)",
    ".fizzle_object(source_id)",
    "lki_object_snapshot(source_id)",
    "lki_object_snapshot(sid)",
    "source_view_live(",
    "source_view_at_resolution(",
];

/// AXIS 2 (SHAPE), deliberately a different matcher from axis 1: find every accessor call
/// in the arm and inspect its ARGUMENTS for a source-flavoured token, whatever the callee's
/// receiver or the argument's spelling.
///
/// Over-collects on purpose. Over-collection can only make `r1` redder.
fn accessor_calls_taking_a_source_argument(squeezed: &str) -> Vec<String> {
    const CALL_HEADS: &[&str] = &[".get(", ".get_mut(", ".object(", "snapshot(", "_object("];
    let mut hits = Vec::new();
    for head in CALL_HEADS {
        let mut from = 0usize;
        while let Some(rel) = squeezed[from..].find(head) {
            let at = from + rel;
            let arg_start = at + head.len();
            // Bound the argument list by its matching paren.
            let b = squeezed.as_bytes();
            let mut depth = 1i32;
            let mut j = arg_start;
            while j < b.len() && depth > 0 {
                match b[j] {
                    b'(' => depth += 1,
                    b')' => depth -= 1,
                    _ => {}
                }
                j += 1;
            }
            let args = &squeezed[arg_start..j.saturating_sub(1).max(arg_start)];
            if args.contains("source") || args.contains("sid") {
                hits.push(format!("{head}{args})"));
            }
            from = at + head.len();
        }
    }
    hits
}

/// CR 608.2h / CR 113.7a. The acceptance criterion's mechanism gate: a new arm that
/// re-reads the source directly is RED.
///
/// Both axes run over every arm. `OOS-DX36-8`: a survivor scan has two axes, the SHAPE of
/// the match and the SPELLING of the value, and varying one while holding the other is half
/// a check. Axis 1 is a literal-needle list (spelling); axis 2 parses argument lists
/// (shape). Neither is a superset of the other: axis 1 catches `source_view_live(` being
/// called from inside an arm (a legal-looking per-arm fallback that axis 2 cannot see,
/// because its argument is a local); axis 2 catches an unforeseen accessor spelling.
#[test]
fn r1_no_filter_arm_reads_the_source_directly() {
    let arms = filter_arms();
    let mut violations: Vec<String> = Vec::new();
    for arm in &arms {
        for needle in DIRECT_SOURCE_READ_NEEDLES {
            if arm.squeezed.contains(needle) {
                violations.push(format!("{} :: axis-1 spelling `{needle}`", arm.name));
            }
        }
        for hit in accessor_calls_taking_a_source_argument(&arm.squeezed) {
            violations.push(format!("{} :: axis-2 shape `{hit}`", arm.name));
        }
    }
    assert!(
        violations.is_empty(),
        "PB-DX39 r1: a filter arm of `effect_applies_to_inner` reads the effect's SOURCE \
         for itself instead of consuming the `source: Option<&SourceView>` the caller \
         supplied. That is the defect this batch closed: twenty arms each had to be right \
         about CR 608.2h and none of them was. Consume `source`; if the arm needs a field \
         the view does not carry, add the field to `SourceView` so BOTH constructors \
         answer it. Violations: {violations:#?}"
    );
    // Non-vacuity floor: the axes must be capable of firing at all.
    let planted = "EffectFilter::Planted=>{state.objects.get(&source_id).map(|s|s.controller)}";
    assert!(
        DIRECT_SOURCE_READ_NEEDLES
            .iter()
            .any(|n| planted.contains(n)),
        "PB-DX39 r1: axis 1 cannot see the very read it was written for"
    );
    assert!(
        !accessor_calls_taking_a_source_argument(planted).is_empty(),
        "PB-DX39 r1: axis 2 cannot see the very read it was written for"
    );
}

