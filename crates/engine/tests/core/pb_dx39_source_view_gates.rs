/// A `ContinuousEffectDef` registered by a **static ability** (CR 611.3a), i.e. one that
/// takes the LIVE path and gets `affected_set: None`.
struct LiveRegistration {
    card: String,
    holder: &'static str,
    filter: String,
    duration: String,
}

/// The JSON variant name of an enum value: `"Unit"` for a unit variant, the single key for
/// a newtype/struct variant.
fn variant_name(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Object(m) if m.len() == 1 => m.keys().next().cloned().unwrap_or_default(),
        other => format!("<unrecognised:{other}>"),
    }
}

fn collect_under_key<'a>(v: &'a Value, key: &str, out: &mut Vec<&'a Value>) {
    match v {
        Value::Object(m) => {
            for (k, child) in m {
                if k == key {
                    out.push(child);
                }
                collect_under_key(child, key, out);
            }
        }
        Value::Array(a) => {
            for child in a {
                collect_under_key(child, key, out);
            }
        }
        _ => {}
    }
}

fn all_ability_lists(def: &CardDefinition) -> Vec<&[AbilityDefinition]> {
    let mut out: Vec<&[AbilityDefinition]> = vec![&def.abilities];
    if let Some(f) = def.back_face.as_ref() {
        out.push(&f.abilities);
    }
    if let Some(f) = def.adventure_face.as_ref() {
        out.push(&f.abilities);
    }
    out
}

/// Every card-def `ContinuousEffectDef` that reaches the engine on the LIVE path.
///
/// Two holders, both enumerated by walking `all_cards()` and never by grepping card source
/// (SR-36):
/// * `AbilityDefinition::Static { continuous_effect }` — registered by `rules/replacement.rs`
///   and by `rules/resolution.rs`'s `StackObjectKind::ClassLevelAbility` arm (CR 716.2a),
///   both of which forward the def's own `duration` verbatim.
/// * `Effect::CreateEmblem { static_effects }` — `effects/mod.rs`'s emblem loop, which uses
///   `EffectDuration::Indefinite` regardless of what the def says.
///
/// Depth-agnostic on both: a `CreateEmblem` can sit inside a `Sequence` inside a mode inside
/// a loyalty ability, and a walk keyed on the parent key measures the parent key.
fn live_path_registrations() -> Vec<LiveRegistration> {
    let mut out = Vec::new();
    for def in all_cards() {
        for abilities in all_ability_lists(&def) {
            for ability in abilities {
                let json = serde_json::to_value(ability).expect("AbilityDefinition serialises");
                let mut defs: Vec<(&'static str, &Value)> = Vec::new();
                let mut found = Vec::new();
                collect_under_key(&json, "continuous_effect", &mut found);
                for f in found {
                    defs.push(("AbilityDefinition::Static", f));
                }
                let mut emblem = Vec::new();
                collect_under_key(&json, "static_effects", &mut emblem);
                for group in emblem {
                    if let Value::Array(items) = group {
                        for item in items {
                            defs.push(("Effect::CreateEmblem", item));
                        }
                    }
                }
                for (holder, ced) in defs {
                    let Some(obj) = ced.as_object() else { continue };
                    let (Some(filter), Some(duration)) = (obj.get("filter"), obj.get("duration"))
                    else {
                        continue;
                    };
                    out.push(LiveRegistration {
                        card: def.name.clone(),
                        holder,
                        filter: variant_name(filter),
                        duration: variant_name(duration),
                    });
                }
            }
        }
    }
    out
}

/// The population an UNCONDITIONAL LKI fallback would have changed the behaviour of --
/// **measured, not argued, and NOT zero.**
///
/// The coordinator's design note predicted this would come out at zero. It does not: the
/// walk finds **4 registrations across 3 cards**, and all four are `Effect::CreateEmblem`
/// static effects with `EffectDuration::Indefinite` and a source-relative filter (Elspeth,
/// Sun's Champion ×2; Kaito, Bane of Nightmares; Wrenn and Seven). Reported rather than
/// rounded to the prediction.
///
/// Splitting the ratchet by HOLDER is what makes the number mean something, because the two
/// holders have different exposure:
///
/// * **`AbilityDefinition::Static` — ratchet 0.** This is the dangerous class. Such a
///   registration's source is a PERMANENT, which can leave the battlefield at any moment,
///   and its duration is forwarded verbatim by `rules/replacement.rs` and by
///   `rules/resolution.rs`'s `StackObjectKind::ClassLevelAbility` arm (CR 716.2a). With an
///   unconditional LKI fallback, a member of this class whose duration is not
///   `WhileSourceOnBattlefield` would START APPLYING from the graveyard, forever. There are
///   none today and there must not be one without someone reading this.
/// * **`Effect::CreateEmblem` — ratchet 4.** CR 114.1: an emblem *"can't be a permanent"*
///   and lives in the command zone, and `effects/mod.rs`'s emblem construction places it in
///   `ZoneId::Command(controller)` with nothing in the engine ever moving it out. Its
///   `ObjectId` is therefore never retired (CR 400.7 never fires on it), so
///   `source_view_live`'s lookup always succeeds and the fallback is unreachable for these
///   four **whichever constructor they used**. They are the SHAPE without the exposure.
///
/// So this row is not evidence that the scoping saved a live defect today. It is evidence
/// that the shape exists in the corpus, that the only thing keeping it harmless is a
/// property of emblems rather than anything about the filter, and that a fifth member
/// arriving under the other holder would be a real one.
const MAX_UNPROTECTED_STATIC_REGISTRATIONS: usize = 0;
const MAX_UNPROTECTED_EMBLEM_REGISTRATIONS: usize = 4;

/// Source-relative + live path + a duration `is_effect_active` does NOT already refuse.
///
/// `WhileSourceOnBattlefield` members are excluded because `is_effect_active` returns
/// `false` for them the moment the source leaves, so no source view of any kind is ever
/// consulted. That exclusion is *why* the residual is the interesting set: it is exactly
/// what `is_effect_active` does not protect.
fn unprotected_live_registrations() -> Vec<(&'static str, String)> {
    let source_relative: BTreeSet<String> =
        SOURCE_RELATIVE_ARMS.iter().map(|s| s.to_string()).collect();
    live_path_registrations()
        .into_iter()
        .filter(|r| source_relative.contains(&r.filter) && r.duration != "WhileSourceOnBattlefield")
        .map(|r| {
            (
                r.holder,
                format!("{} [{}] {} / {}", r.card, r.holder, r.filter, r.duration),
            )
        })
        .collect()
}

