/// One `EffectFilter::X => ...` arm of `effect_applies_to_inner`'s `match &effect.filter`.
struct Arm {
    name: String,
    /// The arm's text, comment-stripped and whitespace-removed.
    squeezed: String,
}

/// Split `effect_applies_to_inner`'s filter match into arms.
///
/// Depth-tracked rather than indentation-tracked: an arm pattern begins at a
/// `EffectFilter::` that sits at brace/paren depth 0 relative to the match body, which is
/// true regardless of how rustfmt has wrapped the file.
fn filter_arms() -> Vec<Arm> {
    let body = fn_body(LAYERS_RS, "effect_applies_to_inner");
    let mat = body
        .find("match &effect.filter")
        .expect("PB-DX39: `match &effect.filter` not found in effect_applies_to_inner");
    let open = body[mat..]
        .find('{')
        .map(|o| mat + o)
        .expect("PB-DX39: no brace after `match &effect.filter`");
    let end = matching_brace(&body, open).expect("PB-DX39: could not brace-match the filter match");
    let inner = &body[open + 1..end];

    let b = inner.as_bytes();
    let mut depth = 0i32;
    let mut starts: Vec<(usize, String)> = Vec::new();
    let mut i = 0usize;
    while i < b.len() {
        match b[i] {
            b'{' | b'(' | b'[' => depth += 1,
            b'}' | b')' | b']' => depth -= 1,
            b'"' => {
                i += 1;
                while i < b.len() && b[i] != b'"' {
                    if b[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
            }
            _ => {}
        }
        if depth == 0 && inner[i..].starts_with("EffectFilter::") {
            let name: String = inner[i + "EffectFilter::".len()..]
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            starts.push((i, name));
        }
        i += 1;
    }
    let mut arms = Vec::new();
    for (idx, (at, name)) in starts.iter().enumerate() {
        let stop = starts.get(idx + 1).map(|(s, _)| *s).unwrap_or(inner.len());
        arms.push(Arm {
            name: name.clone(),
            squeezed: inner[*at..stop]
                .chars()
                .filter(|c| !c.is_whitespace())
                .collect(),
        });
    }
    // Non-vacuity floor: the splitter must actually find the match's arms. A parser that
    // returned `[]` would satisfy every `!contains` assertion below while measuring nothing.
    assert!(
        arms.len() >= 30,
        "PB-DX39: the arm splitter found only {} arms in effect_applies_to_inner (37 at \
         HEAD). The parser has broken and every gate built on it is vacuous; arms: {:?}",
        arms.len(),
        arms.iter().map(|a| &a.name).collect::<Vec<_>>()
    );
    arms
}

